def draw_text(canvas, text, x, y, colour, font=TINY, scale=1):
    """Draw `text` with its top-left at (x, y); returns the x after the last character."""
    for ch in str(text).upper():
        glyph = font.get(ch)
        if glyph is None:
            continue
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            canvas.put(x + gx * scale + dx, y + gy * scale + dy, colour)
        x += (len(glyph[0]) + 1) * scale
    return x


def text_width(text, font=TINY, scale=1):
    widths = [(len(font[ch][0]) + 1) * scale for ch in str(text).upper() if ch in font]
    return sum(widths) - scale if widths else 0
